"""
Export the two migrated legacy presets to scenarios/*.yaml.

Run from the project root:  python scripts/export_legacy_specs.py
The other six legacy presets stay in config/ as archive and are not migrated.
"""

import os
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

import yaml  # noqa: E402

from config.preset_registry import PRESETS  # noqa: E402
from cxsim.legacy import from_legacy_preset  # noqa: E402

# [SECURE] Fixed mapping of preset name to output stem - no user-controlled paths (Category 1)
MIGRATE = {
    "SAP Impact": ("legacy_sap", "Legacy SAP system impact (unvalidated)"),
    "Macro System": ("legacy_macro", "Legacy macro system shock (unvalidated)"),
}


def main() -> None:
    out_dir = ROOT / "scenarios"
    out_dir.mkdir(exist_ok=True)
    for preset_name, (stem, title) in MIGRATE.items():
        spec = from_legacy_preset(PRESETS[preset_name], name=title)
        data = spec.model_dump(mode="json")
        # [SECURE] Atomic write: unpredictable temp file in the target dir, then os.replace (Category 3)
        fd, tmp = tempfile.mkstemp(prefix=f".{stem}.", suffix=".tmp", dir=out_dir)
        try:
            # [SECURE] Context manager guarantees file handle release (Category 5)
            with os.fdopen(fd, "w", encoding="utf-8") as f:
                f.write("# Generated by scripts/export_legacy_specs.py - do not edit by hand.\n")
                yaml.safe_dump(data, f, allow_unicode=True, sort_keys=False)
            os.replace(tmp, out_dir / f"{stem}.yaml")
        except BaseException:
            # [SECURE] Remove the partial temp file, then re-raise - no silent failure (Category 4)
            if os.path.exists(tmp):
                os.remove(tmp)
            raise
        print(f"wrote scenarios/{stem}.yaml ({len(spec.nodes)} nodes, {len(spec.edges)} edges)")


if __name__ == "__main__":
    main()


# --------------------------------------------------
# Security Checklist
# Applied:
#   - Path traversal: output names come from a fixed in-code mapping (Category 1)
#   - Resource release: files written with context managers (Category 5)
#   - Race condition: atomic temp-file + os.replace write (Category 3)
#   - Safe serialization: yaml.safe_dump of validated pydantic data (Category 5)
# Not Applied:
#   - [WARN] Authentication: not applicable - developer-run offline script
